export type KnownIsoCurrencyCode = (typeof ISO_4217_CURRENCY_CODES)[number];
export type IsoCurrencyCode = Brand<KnownIsoCurrencyCode, "IsoCurrencyCode">;

const currencyCodeSet: ReadonlySet<string> = new Set(ISO_4217_CURRENCY_CODES);

export function isIsoCurrencyCode(value: unknown): value is IsoCurrencyCode {
  return typeof value === "string" && currencyCodeSet.has(value);
}

export function parseIsoCurrencyCode(value: unknown): Result<IsoCurrencyCode> {
  if (!isIsoCurrencyCode(value)) {
    return err(
      createCanonicalError({
        category: "validation",
        code: "UNSUPPORTED_VALUE",
        message: "Currency must be a supported ISO 4217 code",
        details: { field: "currency" },
      }),
    );
  }

  return ok(value);
}
