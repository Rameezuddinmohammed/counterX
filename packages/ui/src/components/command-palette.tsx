export interface CommandPaletteProps {
  open?: boolean;
  onOpenChange?: (open: boolean) => void;
  children?: React.ReactNode;
}

export function CommandPalette({
  open,
  onOpenChange,
  children,
}: CommandPaletteProps) {
  return (
    <CommandDialog open={open} onOpenChange={onOpenChange}>
      {children}
    </CommandDialog>
  );
}

